#!/usr/bin/env python3
"""Stdio MCP server exposing the local Bob-wiki retrieval store.

Tools:
  wiki_search(query, top_k, corpus)  - ranked passages with provenance citations
  wiki_ask(question, top_k, model)   - grounded answer from a local Ollama model
  wiki_stats()                       - store health, drift, and model availability

Speaks newline-delimited JSON-RPC 2.0 on stdin/stdout (MCP stdio transport) and
uses only the Python standard library, mirroring tools/rag.py. Retrieval is
read-only: `raw/` and `wiki/` are never modified.

Register it in an MCP client, for example:
  {
    "mcpServers": {
      "bob-rag": {
        "command": "/usr/bin/python3",
        "args": ["/absolute/path/to/tools/rag_mcp.py"],
        "env": {},
        "disabled": false,
        "autoApprove": ["wiki_search", "wiki_stats"],
        "timeout": 120
      }
    }
  }
"""
import importlib.util
import json
import os
import sys
from pathlib import Path

SERVER_NAME = "bob-rag"
SERVER_VERSION = "1.0.0"
SUPPORTED_PROTOCOL_VERSIONS = ("2025-06-18", "2025-03-26", "2024-11-05")
DEFAULT_PROTOCOL_VERSION = "2024-11-05"

_RAG_PATH = Path(__file__).resolve().parent / "rag.py"
_SPEC = importlib.util.spec_from_file_location("bob_rag", _RAG_PATH)
assert _SPEC is not None and _SPEC.loader is not None
rag = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(rag)

TOOLS = [
    {
        "name": "wiki_search",
        "description": (
            "Search the local Bob wiki retrieval index (curated wiki pages plus the "
            "stable extraction chunks of ingested raw sources). Returns ranked passages "
            "with provenance citations such as 'wiki/concepts/qubit.md §Definition' or "
            "'index/extractions/....json p. 42 [src_...:p042:c03]'. Read-only. Always cite "
            "the returned citations and never invent page numbers or chunk IDs."
        ),
        "inputSchema": {
            "type": "object",
            "properties": {
                "query": {"type": "string", "description": "Natural-language search query."},
                "top_k": {
                    "type": "integer", "minimum": 1, "maximum": 25,
                    "description": "Number of passages to return (default 8).",
                },
                "corpus": {
                    "type": "string", "enum": ["all", "wiki", "chunks"],
                    "description": "Corpus to search: curated pages, raw chunks, or both (default all).",
                },
            },
            "required": ["query"],
        },
    },
    {
        "name": "wiki_ask",
        "description": (
            "Answer a question using only passages retrieved from the local wiki index, "
            "generated by a local Ollama model. Citations are returned with the answer. "
            "Fully offline; if the model is unavailable the retrieved passages are returned "
            "instead so the caller can synthesize the answer itself."
        ),
        "inputSchema": {
            "type": "object",
            "properties": {
                "question": {"type": "string", "description": "Question to answer from the wiki."},
                "top_k": {
                    "type": "integer", "minimum": 1, "maximum": 25,
                    "description": "Number of passages used as context (default 6).",
                },
                "model": {
                    "type": "string",
                    "description": f"Local Ollama chat model (default {rag.DEFAULT_CHAT_MODEL}).",
                },
            },
            "required": ["question"],
        },
    },
    {
        "name": "wiki_stats",
        "description": (
            "Report the state of the local retrieval store: indexed file and chunk counts, "
            "embedding model, build time, drift against the current wiki/extraction files, "
            "and which Ollama models are available locally."
        ),
        "inputSchema": {"type": "object", "properties": {}},
    },
]


def send(payload):
    sys.stdout.write(json.dumps(payload, ensure_ascii=False) + "\n")
    sys.stdout.flush()


def result_response(identifier, result):
    return {"jsonrpc": "2.0", "id": identifier, "result": result}


def error_response(identifier, code, message):
    return {"jsonrpc": "2.0", "id": identifier, "error": {"code": code, "message": message}}


def tool_response(text, is_error=False):
    return {"content": [{"type": "text", "text": text}], "isError": bool(is_error)}


def tool_search(arguments):
    query = str(arguments.get("query") or "").strip()
    if not query:
        return tool_response("error: 'query' is required", True)
    try:
        top_k = int(arguments.get("top_k") or 8)
    except (TypeError, ValueError):
        return tool_response("error: 'top_k' must be an integer", True)
    corpora = rag.corpora_for_scope(str(arguments.get("corpus") or "all"))
    results, note = rag.search_chunks(query, corpora=corpora, top_k=top_k)
    if results is None:
        return tool_response(f"error: {note}", True)
    lines = [f"query: {query}", f"corpora: {', '.join(corpora)}"]
    if note:
        lines.append(f"note: {note}")
    lines.append("")
    if not results:
        lines.append("No matching passages.")
    for position, result in enumerate(results, start=1):
        ranks = []
        if result["bm25_rank"]:
            ranks.append(f"bm25 #{result['bm25_rank']}")
        if result["vector_rank"]:
            ranks.append(f"vector #{result['vector_rank']}")
        suffix = f" ({', '.join(ranks)})" if ranks else ""
        lines.append(f"[{position}] {result['citation']}{suffix}")
        lines.append(result["text"])
        lines.append("")
    return tool_response("\n".join(lines).rstrip())


def tool_ask(arguments):
    question = str(arguments.get("question") or "").strip()
    if not question:
        return tool_response("error: 'question' is required", True)
    try:
        top_k = int(arguments.get("top_k") or 6)
    except (TypeError, ValueError):
        return tool_response("error: 'top_k' must be an integer", True)
    model = str(arguments.get("model") or rag.DEFAULT_CHAT_MODEL)
    answer, results, note = rag.ask_question(question, top_k=top_k, model=model)
    if results is None:
        return tool_response(f"error: {note}", True)
    if answer is None:
        passages = "\n\n".join(
            f"[{position}] {result['citation']}\n{result['text']}"
            for position, result in enumerate(results, start=1)
        )
        return tool_response(f"{note}\n\nRetrieved passages:\n\n{passages}")
    citations = "\n".join(f"- {result['citation']}" for result in results)
    text = f"{answer}\n\nSources:\n{citations}"
    if note:
        text += f"\n\nnote: {note}"
    return tool_response(text)


def tool_stats(_arguments):
    return tool_response(rag.format_stats(rag.store_stats()))


HANDLERS = {"wiki_search": tool_search, "wiki_ask": tool_ask, "wiki_stats": tool_stats}


def call_tool(name, arguments):
    handler = HANDLERS.get(name)
    if handler is None:
        return error_response(None, -32602, f"unknown tool: {name}")
    if not isinstance(arguments, dict):
        arguments = {}
    try:
        return handler(arguments)
    except (OSError, ValueError, rag.sqlite3.Error) as exc:
        return tool_response(f"error: {type(exc).__name__}: {exc}", True)


def handle(request):
    """Route one JSON-RPC request; return None for notifications."""
    method = request.get("method")
    identifier = request.get("id")
    params = request.get("params") or {}
    if method == "initialize":
        requested = params.get("protocolVersion")
        version = requested if requested in SUPPORTED_PROTOCOL_VERSIONS else DEFAULT_PROTOCOL_VERSION
        return result_response(identifier, {
            "protocolVersion": version,
            "capabilities": {"tools": {"listChanged": False}},
            "serverInfo": {"name": SERVER_NAME, "version": SERVER_VERSION},
            "instructions": (
                "Local retrieval over the Bob wiki. Call wiki_search before answering "
                "questions about wiki content and cite the returned citations."
            ),
        })
    if method in ("notifications/initialized", "notifications/cancelled"):
        return None
    if method == "ping":
        return result_response(identifier, {})
    if method == "tools/list":
        return result_response(identifier, {"tools": TOOLS})
    if method == "tools/call":
        outcome = call_tool(str(params.get("name")), params.get("arguments") or {})
        if "error" in outcome:
            return outcome
        return result_response(identifier, outcome)
    if identifier is None:
        return None
    return error_response(identifier, -32601, f"method not found: {method}")


def serve():
    """Read newline-delimited JSON-RPC requests until stdin closes."""
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            request = json.loads(line)
        except ValueError:
            send(error_response(None, -32700, "parse error"))
            continue
        if not isinstance(request, dict) or "method" not in request:
            send(error_response(None, -32600, "invalid request"))
            continue
        response = handle(request)
        if response is not None:
            send(response)
    return 0


if __name__ == "__main__":
    sys.exit(serve())